export function categoryIntro(categoryId: string): string {
  switch (categoryId) {
    case "status":
      return "Speech, boundaries, and how much room you need.";
    case "needs":
      return "Body needs, without having to explain them.";
    case "social":
      return "Answers, repair, and asking people to be clearer.";
    case "mine":
      return "Starters you can edit or delete, plus any lines you add.";
    case "favorites":
      return "Buttons you marked as favorites, from any category.";
    default:
      return "Buttons you filed in this category.";
  }
}
